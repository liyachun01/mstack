-- New objects only; never place this in PostgreSQL's existing init directory.
\getenv n8n_password MCP_STACK_N8N_PASSWORD
CREATE ROLE n8n LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
  NOREPLICATION NOBYPASSRLS PASSWORD :'n8n_password';
\unset n8n_password
CREATE DATABASE n8n OWNER n8n TEMPLATE template0;
REVOKE ALL ON DATABASE n8n FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE n8n TO n8n;
\connect n8n
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO n8n;
